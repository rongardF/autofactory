def m3_s_to_cc_s(flowrate_m3_s: float) -> float:
    """Convert cubic meters per second to cubic centimeters per second."""
    return flowrate_m3_s * 1_000_000.0


def cc_to_m3(volume_cc: float) -> float:
    """Convert cubic centimeters to cubic meters."""
    return volume_cc * 1e-6

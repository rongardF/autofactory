"""Launch the conveyor product carrier node.

Selects between the simulated conveyor (Gazebo presence lidar and carrier
joint state bridged into ROS) and real hardware via the ``simulated`` launch
argument. The node starts in the Unconfigured lifecycle state; lifecycle
transitions are driven externally.
"""

from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument, OpaqueFunction
from launch.launch_context import LaunchContext
from launch_ros.actions import Node
from launch.substitutions import LaunchConfiguration


def _launch_node(context: LaunchContext) -> list[Node]:
    """Return the actions to launch, resolved from the launch configuration."""
    simulated = LaunchConfiguration('simulated').perform(context).lower() == 'true'
    node_name = LaunchConfiguration('node_name').perform(context)
    tf_prefix = LaunchConfiguration('tf_prefix').perform(context)

    # Must match the Gazebo topics generated by the conveyor URDF macro.
    presence_topic = f'/{tf_prefix}conveyor/presence_sensor'
    joint_state_topic = f'/{tf_prefix}conveyor/joint_state'

    actions = []
    if simulated:
        actions.append(
            Node(
                package='ros_gz_bridge',
                executable='parameter_bridge',
                name=f'{node_name}_gz_bridge',
                output='screen',
                arguments=[
                    f'{presence_topic}@sensor_msgs/msg/LaserScan[gz.msgs.LaserScan',
                    f'{joint_state_topic}@sensor_msgs/msg/JointState[gz.msgs.Model',
                ],
                remappings=[(joint_state_topic, '/joint_states')],
                parameters=[{'use_sim_time': True}],
            )
        )

    actions.append(
        Node(
            package='product_carrier',
            executable='conveyor',
            name=node_name,
            output='screen',
            parameters=[{
                'simulated': simulated,
                'use_sim_time': simulated,
            }],
            remappings=[('presence_sensor_scan', presence_topic)],
        )
    )

    return actions


def generate_launch_description() -> LaunchDescription:
    """Declare launch arguments and wire up the node selection."""
    ld = LaunchDescription()

    ld.add_action(
        DeclareLaunchArgument(
            'simulated',
            default_value='true',
            description='Use the simulated Gazebo conveyor (true) or real hardware '
            '(false). Real hardware is not implemented yet.',
        )
    )
    ld.add_action(
        DeclareLaunchArgument(
            'node_name',
            default_value='conveyor',
            description='Name of the conveyor node.',
        )
    )
    ld.add_action(
        DeclareLaunchArgument(
            'tf_prefix',
            default_value='',
            description='Prefix used by the conveyor URDF macro; selects the '
            'Gazebo topics to bridge.',
        )
    )

    ld.add_action(OpaqueFunction(function=_launch_node))

    return ld

#!/usr/bin/env bash
# Source this file to load the project environment into the current shell.
# Other shells can read /etc/profile.d, but ROS setup requires Bash.
if [ -z "${BASH_VERSION:-}" ]; then
    return 0
fi

# Activate Python before ROS so colcon uses the project virtual environment.
. /opt/venv/bin/activate
# Prefer project Python packages for nodes using the system Python interpreter.
export PYTHONPATH="/opt/venv/lib/python3.12/site-packages:${PYTHONPATH:-}"
. /opt/ros/jazzy/setup.bash

# The workspace overlay becomes available after the first colcon build.
if [ -f /workspaces/autofactory/install/setup.bash ]; then
    . /workspaces/autofactory/install/setup.bash
fi

# Display settings are generated by the desktop entrypoint after startup.
if [ -f /run/autofactory/rendering.sh ]; then
    . /run/autofactory/rendering.sh
fi
